found as (
    select distinct
        entity,
        currency,
        item_code
    from {{ ref('nbp_bop_observations') }}
),

sheets as (
    select distinct
        entity,
        currency
    from found
)

select
    f.entity,
    f.currency,
    f.item_code,
    'unexpected item' as problem
from found as f
left join expected as e on f.entity = e.entity and f.item_code = e.item_code
where e.item_code is null
union all
select
    s.entity,
    s.currency,
    e.item_code,
    'missing item' as problem
from sheets as s
inner join expected as e on s.entity = e.entity
left join found as f on s.entity = f.entity and s.currency = f.currency and e.item_code = f.item_code
where f.item_code is null
